"""Generate the scorecard at the top of ISSUES.md from each issue's Status and Target lines.

Usage: python scripts/issues_scorecard.py [--check]

Each issue is a `### ISS-NNN - Title` heading followed by a `**Status:**` line. Open work also
carries one fields line:

    **Target:** rc6 · **Priority:** high · **Effort:** M · **Spec:** no · **Evidence:** strong

The scorecard between the scorecard markers is rewritten from those lines. With --check, the
script changes nothing and exits 1 if the scorecard is out of date.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ISSUES = Path(__file__).resolve().parent.parent / "ISSUES.md"
START = "<!-- scorecard:start (generated by scripts/issues_scorecard.py; do not edit) -->"
END = "<!-- scorecard:end -->"
STATUSES = ["open", "in-progress", "blocked", "proposed", "deferred", "done"]
TARGET_ORDER = ["rc6", "rc7", "0.7.0", "0.7.x", "0.8", "later"]
PRIORITY_ORDER = {"high": 0, "medium": 1, "low": 2}

HEADING = re.compile(r"^### (ISS-\d+)\s*[—-]+\s*(.+?)\s*$")
STATUS = re.compile(r"^\*\*Status:\*\*\s*(.*)$")
FIELDS = re.compile(r"^\*\*Target:\*\*")
FIELD = re.compile(r"\*\*(\w+):\*\*\s*([^·]+)")


def parse(text: str) -> list[dict]:
    issues: list[dict] = []
    current: dict | None = None
    for line in text.splitlines():
        heading = HEADING.match(line)
        if heading:
            title = re.sub(r"\s*\((proposed|open question|unverified)\)$", "", heading.group(2))
            current = {"id": heading.group(1), "title": title}
            issues.append(current)
            continue
        if current is None:
            continue
        status = STATUS.match(line)
        if status and "status" not in current:
            word = re.match(r"[a-z-]+", status.group(1).strip().lower())
            value = word.group(0) if word else ""
            if value not in STATUSES:
                raise SystemExit(f"{current['id']}: unknown status {status.group(1)!r}")
            current["status"] = value
        elif FIELDS.match(line):
            for key, value in FIELD.findall(line):
                current[key.lower()] = value.strip()
    for issue in issues:
        if "status" not in issue:
            raise SystemExit(f"{issue['id']}: no **Status:** line")
        if issue["status"] != "done" and "target" not in issue:
            raise SystemExit(f"{issue['id']}: open work needs a **Target:** line")
    return issues


def target_key(target: str) -> str:
    first = target.split()[0]
    return first if first in TARGET_ORDER else "later"


def render(issues: list[dict]) -> str:
    counts = {s: sum(1 for i in issues if i["status"] == s) for s in STATUSES}
    summary = " · ".join(f"{s} {counts[s]}" for s in STATUSES if counts[s])
    lines = [START, "", "## Scorecard", "", f"{len(issues)} issues: {summary}.", ""]
    lines += [
        "| Target | Issue | Title | Status | Priority | Effort | Spec | Evidence |",
        "|---|---|---|---|---|---|---|---|",
    ]
    active = [i for i in issues if i["status"] != "done"]
    active.sort(
        key=lambda i: (
            TARGET_ORDER.index(target_key(i["target"])),
            PRIORITY_ORDER.get(i.get("priority", ""), 3),
            i["id"],
        )
    )
    for i in active:
        lines.append(
            f"| {i['target']} | {i['id']} | {i['title']} | {i['status']} | "
            f"{i.get('priority', '')} | {i.get('effort', '')} | {i.get('spec', '')} | "
            f"{i.get('evidence', '')} |"
        )
    lines += ["", END]
    return "\n".join(lines)


def main() -> int:
    check = "--check" in sys.argv[1:]
    text = ISSUES.read_text()
    if START not in text or END not in text:
        raise SystemExit("ISSUES.md has no scorecard markers")
    before, rest = text.split(START, 1)
    _, after = rest.split(END, 1)
    new = before + render(parse(text)) + after
    if new == text:
        return 0
    if check:
        print("ISSUES.md scorecard is out of date: run python scripts/issues_scorecard.py")
        return 1
    ISSUES.write_text(new)
    print("ISSUES.md scorecard updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
