#!/usr/bin/env python3
"""Merge the diagnostic code fragments into the registry (D-10).

Each work package adds its codes as ``schema/diagnostics/codes.d/<name>.yaml``; this script
merges them into ``schema/diagnostics/codes.yaml``. A code defined in two fragments, or a
severity other than error, warning, or info, is an error.

    python scripts/build_codes.py           # write codes.yaml
    python scripts/build_codes.py --check   # exit 1 if codes.yaml is out of date (used by tests/CI)
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any, Dict

import yaml

REPO = Path(__file__).resolve().parents[3]
DIAGNOSTICS = REPO / "schema" / "diagnostics"
FRAGMENTS = DIAGNOSTICS / "codes.d"
REGISTRY = DIAGNOSTICS / "codes.yaml"
SEVERITIES = {"error", "warning", "info"}
HEADER = (
    "# Diagnostic code registry. Generated by tools/scd-validator/scripts/build_codes.py from\n"
    "# codes.d/; edit the fragments, not this file.\n"
)


def merge(fragments: Path = FRAGMENTS) -> Dict[str, Dict[str, Any]]:
    codes: Dict[str, Dict[str, Any]] = {}
    origin: Dict[str, str] = {}
    for path in sorted(fragments.glob("*.yaml")):
        data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        for code, entry in (data.get("codes") or {}).items():
            if code in codes:
                raise ValueError(f"{code} is defined in both {origin[code]} and {path.name}")
            if not isinstance(entry, dict) or entry.get("severity") not in SEVERITIES:
                raise ValueError(f"{path.name}: {code} needs a severity of error, warning, or info")
            if not entry.get("meaning"):
                raise ValueError(f"{path.name}: {code} needs a meaning")
            codes[code] = {"severity": entry["severity"], "meaning": entry["meaning"]}
            origin[code] = path.name
    return dict(sorted(codes.items()))


def render(codes: Dict[str, Dict[str, Any]]) -> str:
    body = yaml.safe_dump({"codes": codes}, sort_keys=False, allow_unicode=True, width=100)
    return HEADER + "\n" + body


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="only report drift; do not write")
    args = parser.parse_args()
    text = render(merge())
    current = REGISTRY.read_text(encoding="utf-8") if REGISTRY.is_file() else ""
    if args.check:
        if text != current:
            print("codes.yaml is out of date; run: python scripts/build_codes.py")
            return 1
        print("codes.yaml matches codes.d/")
        return 0
    REGISTRY.write_text(text, encoding="utf-8")
    print(f"wrote {REGISTRY.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
